#!/usr/bin/env python3
"""Prepares the bundled caption fonts and writes their metrics for the shared caption layout.

1. Renames every file's family to "RC <Family> <weight>" (one face per family), so libass and the browser pick exactly
   that file by name and never synthesise a weight.
2. Writes packages/shared/src/fontMetrics.ts: units per em, the OS/2 win ascent and descent (libass sizes a font so that
   winAscent + winDescent is the ASS font size), and the advance width of every character from 32 to 255.

Needs fontTools (pip install fonttools). Run from the repo root after scripts/fetch-fonts.sh.
"""
import json, os, re
from fontTools.ttLib import TTFont

DIR = "apps/web/public/fonts"
out = {}
for name in sorted(os.listdir(DIR)):
    if not name.endswith(".ttf"):
        continue
    m = re.match(r"(.+)-(\d+)\.ttf$", name)
    base, weight = m.group(1), int(m.group(2))
    label = re.sub(r"(?<!^)(?=[A-Z])", " ", base).replace("D M ", "DM ")  # PlayfairDisplay -> Playfair Display
    family = f"RC {label} {weight}"
    path = os.path.join(DIR, name)
    f = TTFont(path)
    names = f["name"]
    for rec in list(names.names):
        if rec.nameID in (16, 17, 21, 22):
            names.removeNames(nameID=rec.nameID)
    for pid, eid, lid in ((3, 1, 0x409), (1, 0, 0)):
        names.setName(family, 1, pid, eid, lid)
        names.setName("Regular", 2, pid, eid, lid)
        names.setName(family, 4, pid, eid, lid)
        names.setName(family.replace(" ", ""), 6, pid, eid, lid)
    f["OS/2"].fsSelection = (f["OS/2"].fsSelection & ~0b1100001) | 0b1000000  # REGULAR, not BOLD/ITALIC
    f["head"].macStyle = 0
    f.save(path)
    cmap = f.getBestCmap()
    hmtx = f["hmtx"].metrics
    widths = []
    for code in range(32, 256):
        g = cmap.get(code)
        widths.append(hmtx[g][0] if g else 0)
    known = [w for w in widths[1:95] if w]
    os2 = f["OS/2"]
    out[f"{label}:{weight}"] = {
        "file": name, "family": family, "upm": f["head"].unitsPerEm,
        "winAscent": os2.usWinAscent, "winDescent": os2.usWinDescent,
        "avg": round(sum(known) / len(known)), "widths": widths,
    }

with open("packages/shared/src/fontMetrics.ts", "w") as fh:
    fh.write("// Generated by scripts/make-font-metrics.py from apps/web/public/fonts. Do not edit by hand.\n")
    fh.write("// Per font (\"Family:weight\"): its file, the family name inside it, units per em, OS/2 win ascent and descent,\n")
    fh.write("// the average advance and the advance of every character from 32 to 255 (0 = not in the font).\n")
    fh.write("export type FontMetrics = { file: string; family: string; upm: number; winAscent: number; winDescent: number; avg: number; widths: number[] };\n")
    fh.write("export const FONT_METRICS: Record<string, FontMetrics> = ")
    fh.write(json.dumps(out, separators=(",", ":")))
    fh.write(";\n")
print(len(out), "fonts:", ", ".join(out))
